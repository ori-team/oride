#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn every_l1_language_has_offline_words() {
        for language in [
            LanguageId::OriScript,
            LanguageId::Ori,
            LanguageId::Rust,
            LanguageId::C,
            LanguageId::Bash,
            LanguageId::Python,
            LanguageId::JavaScript,
            LanguageId::TypeScript,
            LanguageId::Tsx,
            LanguageId::Ruby,
            LanguageId::Nim,
            LanguageId::D,
            LanguageId::Lua,
        ] {
            assert!(!completion_words(language).is_empty(), "{language:?}");
        }
    }
}
