//! Catálogos pequenos para completion local quando não há LSP disponível.

use oride_syntax::LanguageId;

pub(crate) fn completion_words(language: LanguageId) -> &'static [&'static str] {
    match language {
        LanguageId::OriScript => ORISCRIPT_WORDS,
        LanguageId::Ori => ORI_WORDS,
        LanguageId::Rust => RUST_WORDS,
        LanguageId::C => C_WORDS,
        LanguageId::Bash => BASH_WORDS,
        LanguageId::Python => PYTHON_WORDS,
        LanguageId::JavaScript | LanguageId::TypeScript | LanguageId::Tsx => WEB_WORDS,
        LanguageId::Ruby => RUBY_WORDS,
        LanguageId::Nim => NIM_WORDS,
        LanguageId::D => D_WORDS,
        LanguageId::Lua => LUA_WORDS,
        LanguageId::Html => HTML_WORDS,
        LanguageId::Css => CSS_WORDS,
        LanguageId::Plain | LanguageId::Markdown | LanguageId::Mdx | LanguageId::Custom(_) => &[],
    }
}

